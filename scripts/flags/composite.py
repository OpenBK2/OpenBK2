#!/usr/bin/env python3
# Build the composite flags of coalition sides: one SVG that lays several member
# drawings out in regions, as a mod's own icon does.
#
# The game has one picture per multiplayer side, so a mod that fields a
# coalition hand-draws a collage of its members into that one 32x22 icon. This
# redraws such a collage sharp: each COMPOSITES entry gives the canvas, in the
# icons' 16:11 frame, and its regions, each a rectangle that one member drawing
# from Flags/Images fills, the way the mod's icon fills it. The fit is an SVG
# preserveAspectRatio value: 'xMinYMin slice' scales the drawing until it
# covers the region and crops it at the far side, which keeps a flag's canton
# when the region is narrower than the flag; 'xMidYMid slice' keeps its middle;
# 'none' stretches the whole drawing to the region, as a mod that squeezes a
# tricolour into a strip does. A region with a polygon is also clipped to it,
# for splits that are not rectangular.
#
# The renderer loads no external files, so the members are copied in, each as a
# nested <svg> with its own viewBox. Their ids are prefixed per member, since
# two drawings may both define id="a" and reuse it.
#
# usage: composite.py            rebuilds every composite in Versions/Current/Data/Flags/Images
import os
import re
import sys
import textwrap

IMAGES = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..',
                      'Versions', 'Current', 'Data', 'Flags', 'Images')

# name: (description, width, height, [(member, (x, y, w, h), fit, polygon or None)])
COMPOSITES = {
    'China_TotalConversion': (
        "Total Conversion's China side: the Republic of China on the left half and the "
        "People's Republic on the right, each showing its canton, as the mod's icon "
        "(Scenario/MPGameRoom/Countries/FlagChinese_Texture.dds) does.",
        320, 220, [
            ('China_Republic', (0, 0, 160, 220), 'xMinYMin slice', None),
            ('China_PeoplesRepublic', (160, 0, 160, 220), 'xMinYMin slice', None),
        ]),
}


def member_svg(name, index, rect, fit):
    """The member drawing as a nested <svg> filling rect, ids prefixed."""
    text = open(os.path.join(IMAGES, name + '.svg'), encoding='utf-8-sig').read()
    text = re.sub(r'<\?xml[^>]*\?>', '', text)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    root = re.search(r'<svg\b[^>]*>', text)
    attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', root.group(0)))
    namespaces = {k: v for k, v in attrs.items() if k.startswith('xmlns:')}
    view_box = attrs.get('viewBox')
    if not view_box:
        view_box = '0 0 %s %s' % (attrs['width'].rstrip('px'), attrs['height'].rstrip('px'))
    body = text[root.end():text.rindex('</svg>')]
    prefix = 'm%d_' % index
    body = re.sub(r'\bid="([^"]+)"', lambda m: 'id="%s%s"' % (prefix, m.group(1)), body)
    body = re.sub(r'(href=")#([^"]+)"', lambda m: '%s#%s%s"' % (m.group(1), prefix, m.group(2)), body)
    body = re.sub(r'url\(#([^)]+)\)', lambda m: 'url(#%s%s)' % (prefix, m.group(1)), body)
    x, y, w, h = rect
    head = '<svg x="%g" y="%g" width="%g" height="%g" viewBox="%s" preserveAspectRatio="%s">' % (
        x, y, w, h, view_box, fit)
    return head + body + '</svg>', namespaces


def build(name):
    description, width, height, parts = COMPOSITES[name]
    namespaces = {'xmlns:xlink': 'http://www.w3.org/1999/xlink'}
    defs, layers = [], []
    for i, (member, rect, fit, polygon) in enumerate(parts):
        svg, ns = member_svg(member, i, rect, fit)
        namespaces.update(ns)
        if polygon:
            defs.append('<clipPath id="region%d"><polygon points="%s"/></clipPath>'
                        % (i, ' '.join('%g,%g' % p for p in polygon)))
            svg = '<g clip-path="url(#region%d)">%s</g>' % (i, svg)
        layers.append(svg)
    members = ', '.join(sorted({p[0] for p in parts}))
    out = '<?xml version="1.0" encoding="UTF-8"?>\n<!--\n'
    note = [
        'Composite flag: ' + description,
        '',
        'Members: %s, from Flags/Images, where each one\'s file records its source and licence. '
        'Generated by scripts/flags/composite.py; edit that and run it again rather than this file.'
        % members,
    ]
    out += '\n'.join(textwrap.fill(par, 78, initial_indent='  ', subsequent_indent='  ') if par else ''
                     for par in note) + '\n-->\n'
    out += '<svg xmlns="http://www.w3.org/2000/svg" %s width="%d" height="%d" viewBox="0 0 %d %d">\n' % (
        ' '.join('%s="%s"' % kv for kv in sorted(namespaces.items())), width, height, width, height)
    if defs:
        out += '<defs>%s</defs>\n' % ''.join(defs)
    out += '\n'.join(layers) + '\n</svg>\n'
    open(os.path.join(IMAGES, name + '.svg'), 'w', encoding='utf-8', newline='\n').write(out)
    print(name + '.svg')


for composite in (sys.argv[1:] or sorted(COMPOSITES)):
    build(composite)
