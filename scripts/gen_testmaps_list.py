#!/usr/bin/env python3
"""Regenerate cmake/testmaps.list, the map files the data tree's records are missing.

A mission is a MapInfo record and a map.b2m, and this repository keeps the two
halves apart: the records are in Versions/Current/Data, the maps under Complete
(and a few under Design), in the layout each record still names in its
MapFilesPath field. The game reads the terrain out of the folder the record is
in, so an install needs the map copied next to its record; cmake/testmaps.cmake
does that from the list this writes.

Only MapFilesPath is believed. Matching by folder name finds plausible pairs
that the data does not actually claim, and a wrong map is worse than none: the
engine reports the size mismatch and generates flat terrain instead, so the
mission loads but is not the authored one.

Only files git knows about are considered, on both sides. That is what makes
this repeatable after an install has already copied maps into the source tree
through the Data symlink, which would otherwise read as records that already
have their map.

    python scripts/gen_testmaps_list.py            # rewrite cmake/testmaps.list
    python scripts/gen_testmaps_list.py --check     # report a stale list, change nothing
"""
import argparse
import os
import re
import subprocess
import sys

DATA = "Versions/Current/Data"
LIST = "cmake/testmaps.list"
# Where a map may come from, best first. A record's MapFilesPath is relative to
# a data root, and these are the roots this repository keeps map files under.
SOURCE_ROOTS = ("Complete", "Design", "")
# Pairs the data claims and the engine rejects, by destination folder. The
# record's MapFilesPath survived a rename or a copy and now names somebody
# else's map, so installing it would load a mission on generated flat terrain
# with a size-mismatch warning rather than on the map it was authored with.
# Measured by starting each of the custom missions in the game.
KNOWN_MISMATCH = {
    # the record is 7x7 patches, Maps/CustomMissions/New Map is 8x8
    "Custom/Missions/Razvedka",
}


def repo_root():
    out = subprocess.run(["git", "rev-parse", "--show-toplevel"],
                         capture_output=True, text=True, check=True)
    return out.stdout.strip()


def tracked_files(root):
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root,
                         capture_output=True, text=True, check=True)
    return [name for name in out.stdout.split("\0") if name]


def decode(raw):
    """The records are a mix of UTF-8 and UTF-16; both spellings are in the tree."""
    if raw[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return raw.decode("utf-16", "ignore")
    if b"\x00" in raw[:64]:
        return raw.decode("utf-16-le", "ignore")
    return raw.decode("utf-8", "ignore")


def map_files_path(path):
    match = re.search(r"<MapFilesPath>(.*?)</MapFilesPath>", decode(open(path, "rb").read()), re.S)
    return match.group(1).strip().replace("\\", "/").strip("/") if match else None


def build_pairs(root):
    tracked = tracked_files(root)
    maps = {}            # lower-cased folder of a tracked map.b2m -> as written
    folders_with_map = set()
    records = []
    for name in tracked:
        lower = name.lower()
        if lower.endswith("/map.b2m"):
            folder = name[: -len("/map.b2m")]
            maps[folder.lower()] = folder
            folders_with_map.add(folder)
        elif lower.endswith(".xdb") and lower.startswith(DATA.lower() + "/"):
            records.append(name)

    pairs = []
    unresolved = []
    for record in records:
        folder = record.rsplit("/", 1)[0]
        if folder in folders_with_map:
            continue  # the map is already where the game looks for it
        filespath = map_files_path(os.path.join(root, record))
        if not filespath:
            continue  # not a map record
        source = None
        for prefix in SOURCE_ROOTS:
            candidate = ("%s/%s" % (prefix, filespath)) if prefix else filespath
            if candidate.lower() in maps:
                source = maps[candidate.lower()]
                break
        if source is None:
            unresolved.append(record)
            continue
        destination = folder[len(DATA) + 1:]
        if destination in KNOWN_MISMATCH:
            continue
        pairs.append((destination, source + "/map.b2m"))

    # One line per destination folder: several records can share a folder, and
    # they name the same map when they do.
    deduped = {}
    for destination, source in pairs:
        deduped.setdefault(destination, source)
    return sorted(deduped.items(), key=lambda item: item[0].lower()), unresolved


def render(pairs, root):
    total = 0
    for _, source in pairs:
        total += os.path.getsize(os.path.join(root, source))
    lines = [
        "# Generated by scripts/gen_testmaps_list.py; do not edit by hand.",
        "#",
        "# <folder under Data/Custom, Data/Maps, ...>|<map file in this repository>",
        "#",
        "# One line per map record in Versions/Current/Data that has no map.b2m beside",
        "# it and whose own MapFilesPath names one that this repository does have.",
        "# cmake/testmaps.cmake installs each into Data/<folder>/map.b2m.",
        "#",
        "# %d maps, %.1f MB." % (len(pairs), total / 1048576.0),
    ]
    lines += ["%s|%s" % pair for pair in pairs]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report a stale list, change nothing")
    args = parser.parse_args()

    root = repo_root()
    pairs, unresolved = build_pairs(root)
    text = render(pairs, root)
    path = os.path.join(root, LIST)

    if args.check:
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if current != text:
            print("%s is out of date; run python scripts/gen_testmaps_list.py" % LIST)
            return 1
        print("%s is up to date: %d maps" % (LIST, len(pairs)))
        return 0

    open(path, "w", encoding="utf-8", newline="\n").write(text)
    print("%s: %d maps" % (LIST, len(pairs)))
    print("records with no map anywhere in the repository: %d" % len(unresolved))
    return 0


if __name__ == "__main__":
    sys.exit(main())
